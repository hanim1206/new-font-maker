test('혼합중성의 가로부와 세로부를 각각 레이아웃 박스로 선택한다', async ({ page }) => {
  await page.getByRole('button', { name: '중성 ㅗ 캐러셀 기준으로 선택' }).click()
  for (let index = 0; index < 19; index += 1) await page.getByRole('button', { name: /^다음 중성 글자/ }).click()
  await page.getByRole('button', { name: '현재 글자의 레이아웃 편집 열기' }).click()
  await expect(page.getByRole('button', { name: /가로부 레이아웃 박스 활성/ })).toBeVisible()
  const verticalPart = page.getByRole('button', { name: /세로부 레이아웃 박스 활성/ })
  await expect(verticalPart).toBeVisible()
  await verticalPart.click()
  await expect(page.getByRole('button', { name: /세로부 위쪽 여백 조절/ })).toBeVisible()
  await expect(page.getByRole('button', { name: /세로부 오른쪽 여백 조절/ })).toBeVisible()
  const bottomEdge = page.getByRole('button', { name: /세로부 아래쪽 여백 조절/ })
  const before = await bottomEdge.boundingBox()
  if (!before) throw new Error('혼합중성 세로부 아래쪽 경계를 찾지 못했습니다.')
  await page.mouse.move(before.x + before.width / 2, before.y + before.height / 2)
  await page.mouse.down()
  await page.mouse.move(before.x + before.width / 2, before.y + before.height / 2 + 20, { steps: 4 })
  await page.mouse.up()
  const after = await bottomEdge.boundingBox()
  expect(after?.y ?? 0).toBeGreaterThan(before.y)
})

