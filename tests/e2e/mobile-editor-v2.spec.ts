test('가로·세로 모음 기본형은 각각의 모음 박스 비율로 표시한다', async ({ page }) => {
  await page.getByRole('button', { name: '중성 ㅗ 캐러셀 기준으로 선택' }).click()
  await page.getByRole('button', { name: /^ㅗ .* 획 선택$/ }).first().focus()
  await page.keyboard.press('Enter')
  const horizontalPreview = page.getByRole('region', { name: 'ㅗ 단독 미리보기' })
  const horizontalBox = await horizontalPreview.boundingBox()
  if (!horizontalBox) throw new Error('가로 모음 기본형 미리보기를 찾지 못했습니다.')
  expect(horizontalBox.width).toBeGreaterThan(horizontalBox.height * 1.5)

  await page.getByRole('button', { name: '뒤로' }).click()
  for (let index = 0; index < 21 && await page.getByRole('button', { name: '중성 ㅏ 캐러셀 기준으로 선택' }).count() === 0; index += 1) {
    await page.getByRole('button', { name: /^이전 중성 글자/ }).click()
  }
  await page.getByRole('button', { name: /^ㅏ .* 획 선택$/ }).first().focus()
  await page.keyboard.press('Enter')
  const verticalPreview = page.getByRole('region', { name: 'ㅏ 단독 미리보기' })
  const verticalBox = await verticalPreview.boundingBox()
  if (!verticalBox) throw new Error('세로 모음 기본형 미리보기를 찾지 못했습니다.')
  expect(verticalBox.height).toBeGreaterThan(verticalBox.width * 1.5)
})

test('기본형 화면에서만 개별 획과 꼭지점으로 들어간다', async ({ page }) => {
  await page.getByRole('button', { name: 'ㄱ ㄱ-1 획 선택' }).focus()
  await page.keyboard.press('Enter')
  const stroke = page.getByRole('button', { name: 'ㄱ ㄱ-1 획 선택' })
  await stroke.focus()
  await page.keyboard.press('Enter')
  const startPoint = page.locator('[aria-label="ㄱ ㄱ-1 시작 꼭짓점 선택"]')
  await expect(startPoint).toBeVisible()
  await startPoint.click()
  await expect(page.getByRole('group', { name: '한 손가락으로 이동하고 두 손가락으로 획 비율을 조절하는 트랙패드' })).toBeVisible()
  await expect(page.getByRole('complementary', { name: '획 편집 도구' })).toBeVisible()
  await page.getByRole('button', { name: '곡선화' }).click()
  await expect(page.getByRole('button', { name: '직선화' })).toBeVisible()
  const curveHandle = page.getByRole('button', { name: /시작 꼭짓점 나가는 곡선 손잡이 선택/ })
  await expect(curveHandle).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('navigation', { name: '현재 선택 단계' })).toContainText('나가는 곡선 손잡이')
  const handleXBefore = Number(await curveHandle.getAttribute('cx'))
  const curveTrackpad = page.getByRole('group', { name: '한 손가락으로 이동하고 두 손가락으로 획 비율을 조절하는 트랙패드' })
  await curveTrackpad.focus()
  await page.keyboard.press('ArrowRight')
  expect(Number(await curveHandle.getAttribute('cx'))).toBeGreaterThan(handleXBefore)
  await page.getByRole('button', { name: '직선화' }).click()
  await expect(curveHandle).toHaveCount(0)
  await page.getByRole('button', { name: '방향 잠금' }).click()
  await page.locator('[aria-label="ㄱ ㄱ-1 끝 꼭짓점 선택"]').click()
  const unlock = page.getByRole('button', { name: '방향 잠금 해제' })
  await expect(unlock).toHaveAttribute('aria-pressed', 'true')
  await unlock.click()
  await expect(page.getByRole('button', { name: '방향 잠금' })).toHaveAttribute('aria-pressed', 'false')
  await page.getByRole('button', { name: '선 추가' }).click()
  const addedStroke = page.getByRole('button', { name: /^ㄱ stroke-\d+ 획 선택$/ })
  await expect(addedStroke).toHaveCount(1)
  await expect(addedStroke).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: '획 삭제' }).click()
  await expect(addedStroke).toHaveCount(0)
  await page.getByRole('button', { name: '뒤로' }).click()
  await expect(page.getByRole('heading', { name: '곰 편집' })).toBeVisible()
  await expect(page.getByText('글자 속 자소를 누르면 상세 편집으로 이동합니다')).toBeVisible()
  await expect(page.locator('[aria-label="ㄱ ㄱ-1 시작 꼭짓점 선택"]')).toHaveCount(0)
})

